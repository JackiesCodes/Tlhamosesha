// Self-hosts the poster font library: copies the Latin woff2 files from the
// @fontsource packages into public/fonts and writes public/fonts/fonts.css
// with plain family names ("Inter", not "Inter Variable"). Font matching
// renders every candidate on a canvas, so the fonts must load reliably and
// without a third-party request.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const VARIABLE = ["Inter", "Montserrat", "Oswald", "Playfair Display", "Roboto", "Roboto Slab", "Raleway", "Open Sans", "Space Grotesk", "JetBrains Mono", "League Spartan", "Merriweather", "Archivo"];
const STATIC = {
  Anton: [400],
  "Bebas Neue": [400],
  "Archivo Black": [400],
  Poppins: [300, 400, 500, 600, 700, 800, 900],
  Lato: [300, 400, 700, 900],
  Pacifico: [400],
  Lobster: [400],
  "DM Serif Display": [400],
  "Barlow Condensed": [400, 500, 600, 700, 800],
};
const slug = (f) => f.toLowerCase().replace(/ /g, "-");
const out = "public/fonts";
mkdirSync(join(out, "files"), { recursive: true });

const sources = [
  ...VARIABLE.map((f) => ({ family: f, dir: `node_modules/@fontsource-variable/${slug(f)}`, css: ["index.css"] })),
  ...Object.entries(STATIC).map(([f, ws]) => ({ family: f, dir: `node_modules/@fontsource/${slug(f)}`, css: ws.map((w) => `${w}.css`) })),
];
let css = "/* Generated by scripts/copy-font-assets.mjs (SIL Open Font License fonts via Fontsource). */\n";
let missing = 0;
for (const s of sources) {
  for (const file of s.css) {
    const p = join(s.dir, file);
    if (!existsSync(p)) {
      missing++;
      continue;
    }
    for (const block of readFileSync(p, "utf8").match(/@font-face\s*{[^}]*}/g) ?? []) {
      const url = block.match(/url\(\.\/files\/([^)]+)\)/)?.[1];
      if (!url || !/-latin-(ext-)?/.test(url) || /italic/.test(url)) continue;
      copyFileSync(join(s.dir, "files", url), join(out, "files", url));
      css += block.replace(/font-family:\s*'[^']+'/, `font-family: '${s.family}'`).replace(`url(./files/${url})`, `url(/fonts/files/${url})`) + "\n";
    }
  }
}
writeFileSync(join(out, "fonts.css"), css);
if (missing) console.warn(`[fonts] ${missing} font stylesheets not found — some fonts will fall back.`);
console.log("[fonts] Wrote public/fonts/fonts.css");
